#define main probe_main
#include "tee-probe.c"
#undef main
#include <assert.h>

int main(void)
{
    char directory[]="/tmp/moto70-fingerprint-test-XXXXXX";
    assert(mkdtemp(directory));
    fs.directory=open(directory,O_RDONLY|O_DIRECTORY);
    assert(fs.directory>=0);
    for (int i=0;i<8;i++) fs.files[i]=-1;
    int fixture=openat(fs.directory,"jv_opt_data.bin",O_WRONLY|O_CREAT|O_EXCL,0600);
    assert(fixture>=0 && write(fixture,"test",4)==4);
    close(fixture);
    tz_file_open_req_t req={.cmd_id=TZ_FS_MSG_CMD_FILE_OPEN};
    strcpy(req.pathname,"/mnt/vendor/persist/jiiov/jv_opt_data.bin");
    int handle=fs_open(&req);
    assert(handle==100);
    req.flags=O_WRONLY;
    assert(fs_open(&req)==-1 && errno==EROFS);
    req.flags=O_RDONLY;
    strcpy(req.pathname,"/mnt/vendor/persist/jiiov/../../etc/shadow");
    assert(fs_open(&req)==-1 && errno==EACCES);
    memset(req.pathname,'x',sizeof(req.pathname));
    assert(fs_open(&req)==-1 && errno==EACCES);
    assert(symlinkat("/etc/passwd",fs.directory,"jv_normalized_calibration.bin")==0);
    strcpy(req.pathname,"/mnt/vendor/persist/jiiov/jv_normalized_calibration.bin");
    assert(fs_open(&req)==-1 && errno==ELOOP);

    union { uint64_t alignment; unsigned char bytes[FILE_SERVICE_BUF_LEN]; } data={0};
    tz_file_read_req_t read_req={.cmd_id=TZ_FS_MSG_CMD_FILE_READ,.fd=handle,.count=4};
    memcpy(data.bytes,&read_req,sizeof(read_req));
    assert(fs_dispatch(data.bytes)==0);
    tz_file_read_rsp_t *read_rsp=(void *)data.bytes;
    assert(read_rsp->ret==4 && memcmp(read_rsp->buf,"test",4)==0);
    read_req.count=TZ_CM_MAX_DATA_LEN+1;
    memcpy(data.bytes,&read_req,sizeof(read_req));
    assert(fs_dispatch(data.bytes)==0 && read_rsp->ret==-1 && fs.last_errno==EINVAL);
    read_req.fd=1000;
    memcpy(data.bytes,&read_req,sizeof(read_req));
    assert(fs_dispatch(data.bytes)==0 && read_rsp->ret==-1 && fs.last_errno==EBADF);
    uint32_t unsupported=TZ_FS_MSG_CMD_FILE_WRITE;
    memcpy(data.bytes,&unsupported,4);
    assert(fs_dispatch(data.bytes)==2);
    void *gp=calloc(1,GPFILE_SERVICE_BUF_LEN);
    assert(gp);
    tz_gpfile_read_req_t gp_req={.cmd_id=TZ_GPFS_MSG_CMD_PERSIST_FILE_READ,.count=3,.offset=1};
    strcpy(gp_req.pathname,"jiiov/jv_opt_data.bin");
    memcpy(gp,&gp_req,sizeof(gp_req));
    assert(gp_dispatch(gp)==0);
    tz_gpfile_read_rsp_t *gp_rsp=gp;
    assert(gp_rsp->err==0 && gp_rsp->num_bytes_read==3 && memcmp(gp_rsp->buf,"est",3)==0);
    gp_req.cmd_id=0;
    strcpy(gp_req.pathname,"/mnt/vendor/persist/jiiov/jv_opt_data.bin");
    memcpy(gp,&gp_req,sizeof(gp_req));
    assert(gp_dispatch(gp)==0 && gp_rsp->num_bytes_read==3 && memcmp(gp_rsp->buf,"est",3)==0);
    gp_req.count=504*1024-12+1;
    memcpy(gp,&gp_req,sizeof(gp_req));
    assert(gp_dispatch(gp)==0 && gp_rsp->err==EINVAL);
    gp_req.count=4;
    strcpy(gp_req.pathname,"jiiov/../../etc/passwd");
    memcpy(gp,&gp_req,sizeof(gp_req));
    assert(gp_dispatch(gp)==0 && gp_rsp->err==EACCES);
    gp_req.cmd_id=TZ_GPFS_MSG_CMD_PERSIST_FILE_WRITE;
    memcpy(gp,&gp_req,sizeof(gp_req));
    assert(gp_dispatch(gp)==2);
    assert(mkdirat(fs.directory,"templates",0700)==0);
    fs.storage_directory=openat(fs.directory,"templates",O_RDONLY|O_DIRECTORY);
    assert(fs.storage_directory>=0);
    const char *template_path="/droidloom-fingerprint-probe/template_941001.db.0";
    assert(fs_template_name(template_path,strlen(template_path)+1));
    assert(!fs_template_name(template_path,strlen(template_path)));
    assert(!fs_template_name("/droidloom-fingerprint-probe/template_941001.db.64",256));
    assert(!fs_template_name("/droidloom-fingerprint-probe/template_941001.db.5",256));
    assert(fs_template_name("/droidloom-fingerprint-probe/template_941001.db.bak.4",256));
    assert(!fs_template_name("/droidloom-fingerprint-probe/template_941001.db.00",256));
    assert(!fs_template_name("/droidloom-fingerprint-probe/template_941002.db.0",256));
    assert(!fs_template_name("/droidloom-fingerprint-probe/../template_941001.db.0",256));
    assert(fs_template_name("/droidloom-fingerprint-probe/template_941001_0.0",256));
    assert(fs_template_name("/droidloom-fingerprint-probe/template_941001_4.bak.4",256));
    assert(!fs_template_name("/droidloom-fingerprint-probe/template_941001_5.0",256));
    assert(!fs_template_name("/droidloom-fingerprint-probe/template_941001_00.0",256));
    assert(!fs_template_name("/droidloom-fingerprint-probe/template_941001_0_images.image_0",256));
    tz_gpfile_write_req_t *write_req=gp;
    memset(gp,0,GPFILE_SERVICE_BUF_LEN);
    write_req->cmd_id=1;
    strcpy(write_req->pathname,template_path);
    write_req->count=4;
    memcpy(write_req->buf,"data",4);
    assert(gp_dispatch(gp)==0);
    assert(anc_get_le32((char *)gp+4)==0 && anc_get_le32((char *)gp+8)==4);
    gp_req=(tz_gpfile_read_req_t){.cmd_id=0,.count=4};
    strcpy(gp_req.pathname,template_path);
    memcpy(gp,&gp_req,sizeof(gp_req));
    assert(gp_dispatch(gp)==0 && gp_rsp->num_bytes_read==4 && !memcmp(gp_rsp->buf,"data",4));
    memset(gp,0,GPFILE_SERVICE_BUF_LEN);
    write_req->cmd_id=1;
    strcpy(write_req->pathname,template_path);
    write_req->offset=1024*1024+52;
    write_req->count=1;
    assert(gp_dispatch(gp)==0 && anc_get_le32((char *)gp+4)==EINVAL);
    /* The final encrypted header bytes cross the old 512 KiB limit. */
    memset(gp,0,GPFILE_SERVICE_BUF_LEN);
    write_req->cmd_id=1;
    strcpy(write_req->pathname,template_path);
    write_req->offset=1024*1024+51;
    write_req->count=1;
    write_req->buf[0]=0xa5;
    assert(gp_dispatch(gp)==0 && anc_get_le32((char *)gp+4)==0);
    gp_req.offset=1024*1024+51;
    gp_req.count=1;
    memcpy(gp,&gp_req,sizeof(gp_req));
    assert(gp_dispatch(gp)==0 && gp_rsp->num_bytes_read==1 && gp_rsp->buf[0]==0xa5);
    memset(gp,0,GPFILE_SERVICE_BUF_LEN);
    write_req->cmd_id=1;
    strcpy(write_req->pathname,"/mnt/vendor/persist/jiiov/jv_opt_data.bin");
    assert(gp_dispatch(gp)==0 && anc_get_le32((char *)gp+4)==EACCES);
    assert(symlinkat("/etc/passwd",fs.storage_directory,"template_941001.db.1")==0);
    assert(fs_storage_open("template_941001.db.1",O_WRONLY)==-1 && errno==ELOOP);
    tz_gpfile_rename_req_t rename_req={.cmd_id=3};
    strcpy(rename_req.from,template_path);
    strcpy(rename_req.to,"/droidloom-fingerprint-probe/template_941001.db.bak.0");
    memcpy(gp,&rename_req,sizeof(rename_req));
    assert(gp_dispatch(gp)==0 && anc_get_le32((char *)gp+4)==0);
    tz_gpfile_remove_req_t remove_req={.cmd_id=2};
    strcpy(remove_req.pathname,rename_req.to);
    memcpy(gp,&remove_req,sizeof(remove_req));
    assert(gp_dispatch(gp)==0 && anc_get_le32((char *)gp+4)==0);
    unlinkat(fs.storage_directory,"template_941001.db.1",0);
    /* Replay the observed maximal request using synthetic bytes. The last
     * payload byte is the final byte of the registered callback mapping.
     */
    memset(gp,0,GPFILE_SERVICE_BUF_LEN);
    write_req->cmd_id=1;
    strcpy(write_req->pathname,"/droidloom-fingerprint-probe/template_941001_0.0");
    write_req->count=515824;
    ((unsigned char *)gp)[504*1024-1]=0x5a;
    assert(gp_dispatch(gp)==0 && anc_get_le32((char *)gp+8)==515824);
    gp_req=(tz_gpfile_read_req_t){.cmd_id=0,.count=515824};
    strcpy(gp_req.pathname,"/droidloom-fingerprint-probe/template_941001_0.0");
    memcpy(gp,&gp_req,sizeof(gp_req));
    assert(gp_dispatch(gp)==0 && gp_rsp->num_bytes_read==515824);
    assert(((unsigned char *)gp)[12+515824-1]==0x5a);
    memset(gp,0,GPFILE_SERVICE_BUF_LEN);
    write_req->cmd_id=1;
    strcpy(write_req->pathname,gp_req.pathname);
    write_req->count=515825;
    assert(gp_dispatch(gp)==0 && anc_get_le32((char *)gp+4)==EINVAL);
    assert(unlinkat(fs.storage_directory,"template_941001_0.0",0)==0);
    close(fs.storage_directory); fs.storage_directory=-1;
    assert(unlinkat(fs.directory,"templates",AT_REMOVEDIR)==0);
    free(gp);
    close(fs.files[0]); fs.files[0]=-1;
    unlinkat(fs.directory,"jv_opt_data.bin",0);
    unlinkat(fs.directory,"jv_normalized_calibration.bin",0);
    close(fs.directory); fs.directory=-1;
    assert(rmdir(directory)==0);
    puts("Calibration listener boundary tests passed.");
    return 0;
}
